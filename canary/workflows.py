"""The per-state workflows and the README's table of states, generated from
states.STATES.

Each is a thin caller of the reusable check-state.yml: its own schedule, run
history, status badge, manual run button and on/off switch, with the steps in
one place. `--check` (run in CI) fails when a file is missing, stale or left
over from a removed state.
"""

from __future__ import annotations

from pathlib import Path

from .states import STATES, State, cron

ROOT = Path(__file__).resolve().parent.parent
WORKFLOWS = ROOT / ".github" / "workflows"
README = ROOT / "README.md"
PREFIX = "state-"
TABLE_START, TABLE_END = "<!-- states:start -->", "<!-- states:end -->"

TEMPLATE = """\
# Generated by `python -m canary workflows --write` from canary/states.py: edit
# there, not here. The steps live in check-state.yml.
name: {code_upper} {name}

on:
  schedule:
    - cron: "{cron}"
  workflow_dispatch:
    inputs:
      all_cases:
        description: Check every sample id, not just this run's two
        type: boolean
        default: false

permissions: {{}}

# Per branch, so a test run from a branch never replaces a pending run of main.
concurrency:
  group: state-{code}-${{{{ github.ref }}}}
  cancel-in-progress: false

jobs:
  check:
    uses: ./.github/workflows/check-state.yml
    with:
      state: {code}
      all_cases: ${{{{ inputs.all_cases == true }}}}
    secrets:
      CHECKER_BASE_URL: ${{{{ secrets.CHECKER_BASE_URL }}}}
    permissions:
      contents: read # check out this repository
      issues: write # open, comment on and close the state's issue
"""


def path(state: State) -> Path:
    return WORKFLOWS / f"{PREFIX}{state.code}.yml"


def render(state: State) -> str:
    return TEMPLATE.format(code=state.code, code_upper=state.code.upper(), name=state.name, cron=cron(state))


def table(repo: str = "vvAlpha/state-checker-canary") -> str:
    """The README's table of states: group, schedule and status badge, one row each."""
    rows = ["| State | Group | Runs at (UTC) | Last run |", "|---|---|---|---|"]
    for s in STATES:
        minute, hours, *_ = cron(s).split()
        first = int(hours.split("-")[0])
        times = ", ".join(f"{h:02d}:{int(minute):02d}" for h in range(first, 24, 3)[:2]) + ", ..."
        url = f"https://github.com/{repo}/actions/workflows/{path(s).name}"
        rows.append(f"| {s.code.upper()} {s.name} | {s.group} | {times} | [![{s.code}]({url}/badge.svg)]({url}) |")
    return "\n".join(rows)


def _readme_with_table(text: str) -> str:
    head, _, rest = text.partition(TABLE_START)
    _, _, tail = rest.partition(TABLE_END)
    return f"{head}{TABLE_START}\n{table()}\n{TABLE_END}{tail}"


def drift() -> list[str]:
    """What differs between the table and the files on disk."""
    problems = []
    for s in STATES:
        p = path(s)
        if not p.exists():
            problems.append(f"{p.name}: missing")
        elif p.read_text() != render(s):
            problems.append(f"{p.name}: out of date")
    wanted = {path(s).name for s in STATES}
    for p in sorted(WORKFLOWS.glob(f"{PREFIX}*.yml")):
        if p.name not in wanted:
            problems.append(f"{p.name}: no such state in canary/states.py")
    text = README.read_text() if README.exists() else ""
    if TABLE_START not in text or TABLE_END not in text:
        problems.append("README.md: missing the states table markers")
    elif _readme_with_table(text) != text:
        problems.append("README.md: states table out of date")
    return problems


def write() -> list[str]:
    changed = []
    for s in STATES:
        p = path(s)
        text = render(s)
        if not p.exists() or p.read_text() != text:
            p.write_text(text)
            changed.append(p.name)
    text = README.read_text() if README.exists() else ""
    if TABLE_START in text and TABLE_END in text and _readme_with_table(text) != text:
        README.write_text(_readme_with_table(text))
        changed.append(README.name)
    return changed
